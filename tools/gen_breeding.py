#!/usr/bin/env python3
"""Writes src/breeding.inc: what the Day Care, Eggs and EVs need for each Pokemon, from a PokeAPI checkout's CSVs:
egg groups, gender ratio, egg cycles, EV yield, what species hatches from its Eggs, and its egg moves.
    python tools/gen_breeding.py <path to pokeapi/data/v2/csv>
"""
import csv, os, sys, unicodedata, collections
P = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = lambda f: list(csv.DictReader(open(os.path.join(P, f), encoding='utf-8')))
def asc(s):
    s = s.replace('♀', ' F').replace('♂', ' M').replace('’', "'").replace('—', '-').replace('–', '-')
    return unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().replace(':', '')
species = {int(r['id']): r for r in rows('pokemon_species.csv') if int(r['id']) <= 809}
name = {int(r['pokemon_species_id']): asc(r['name']) for r in rows('pokemon_species_names.csv')
        if r['local_language_id'] == '9' and int(r['pokemon_species_id']) in species}
egname = {r['id']: r['identifier'] for r in rows('egg_groups.csv')}
EGG = {'monster': 'Monster', 'water1': 'Water 1', 'bug': 'Bug', 'flying': 'Flying', 'ground': 'Field', 'fairy': 'Fairy',
       'plant': 'Grass', 'humanshape': 'Human-Like', 'water3': 'Water 3', 'mineral': 'Mineral', 'indeterminate': 'Amorphous',
       'water2': 'Water 2', 'ditto': 'Ditto', 'dragon': 'Dragon', 'no-eggs': 'Undiscovered'}
groups = collections.defaultdict(list)
for r in rows('pokemon_egg_groups.csv'):
    s = int(r['species_id'])
    if s in species: groups[s].append(EGG[egname[r['egg_group_id']]])
ev = collections.defaultdict(lambda: [0] * 6)
for r in rows('pokemon_stats.csv'):
    s = int(r['pokemon_id'])
    if s in species: ev[s][int(r['stat_id']) - 1] = int(r['effort'])
INCENSE = {298, 360, 406, 433, 438, 439, 440, 446, 458}   # babies that hatch only with an incense: without one, the next stage
def egg_of(s):
    while True:
        f = species[s]['evolves_from_species_id']
        if not f: return s
        f = int(f)
        if f in INCENSE: return s
        s = f
mn = {r['move_id']: asc(r['name']) for r in rows('move_names.csv') if r['local_language_id'] == '9'}
eggm = collections.defaultdict(lambda: collections.defaultdict(set))
for r in rows('pokemon_moves.csv'):
    s = int(r['pokemon_id'])
    if s in species and r['pokemon_move_method_id'] == '2': eggm[s][r['version_group_id']].add(mn[r['move_id']])
order = ['25', '23', '20', '18', '17', '16', '15', '14', '10', '9']
out = ['// Generated by tools/gen_breeding.py from PokeAPI: for the Day Care, Eggs and EVs.',
       '// {name, egg group 1, egg group 2, gender (-1 genderless, else eighths female), egg cycles, EV yield HP/Atk/Def/SpA/SpD/Spe,',
       '//  what hatches from its Eggs, egg moves "a|b|c"}',
       'static const BreedInfo kBreed[] = {']
for s in sorted(species):
    sp = species[s]
    g = groups[s] + ['', '']
    vg = next((v for v in order if eggm[s][v]), None)
    moves = '|'.join(sorted(eggm[s][vg])) if vg else ''
    e = ev[s]
    out.append('    {"%s", "%s", "%s", %s, %s, {%s}, "%s", "%s"},' % (name[s], g[0], g[1], sp['gender_rate'], sp['hatch_counter'],
               ', '.join(map(str, e)), name[egg_of(s)], moves))
out.append('};')
open(os.path.join(ROOT, 'src', 'breeding.inc'), 'w').write('\n'.join(out) + '\n')
print(len(species), 'species')

#!/usr/bin/env python3
"""Emerald's berries, from pret/pokeemerald: the table the game grows them with (src/berries.inc) and the berry
trees' pictures (World/berrytrees.png).

    emerald_berries.py <pokeemerald dir> [World dir] [src dir]

src/berries.inc: {name, hours per growth stage, most berries, fewest berries, spicy, dry, sweet, bitter, sour, smoothness}
World/berrytrees.png: one row per berry in that order, nine 16x32 cells: soil, sprout x2, growing x2, flowering x2,
berries x2 - each stage in the palette Emerald gives it (gBerryTreePaletteSlotTable_*)."""
import os, re, sys
from PIL import Image

E = sys.argv[1]
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "World")
SRC = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, "src")
PICS = os.path.join(E, "graphics/object_events/pics/berry_trees")


def jasc(path):
    v = open(path).read().split()
    n = int(v[2])
    return [tuple(map(int, v[3 + i * 3:6 + i * 3])) for i in range(n)]


NPC = {2 + k: jasc(os.path.join(E, "graphics/object_events/palettes/npc_%d.pal" % (k + 1))) for k in range(4)}

src = open(os.path.join(E, "src/berry.c")).read()
i = src.index("gBerries[]")
src = src[i:src.index("};", i)]
berries = []
for m in re.finditer(r"\{\s*\.name = _\(\"(\w+)\"\),(.*?)\n    \},", src, re.S):
    b = m.group(2)
    g = lambda k: int(re.search(r"\." + k + r"\s*=\s*([^,]+),", b).group(1))
    berries.append((m.group(1).title(), g("stageDuration"), g("maxYield"), g("minYield"),
                    [g(k) for k in ("spicy", "dry", "sweet", "bitter", "sour")], g("smoothness")))
tables = open(os.path.join(E, "src/data/object_events/berry_tree_graphics_tables.h")).read()
slots = {n: list(map(int, v.split(","))) for n, v in re.findall(r"gBerryTreePaletteSlotTable_(\w+)\[\] = \{([^}]*)\}", tables)}


def recolour(im, pal):
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    src_px, dst = im.load(), out.load()
    for y in range(im.height):
        for x in range(im.width):
            c = src_px[x, y] & 15
            if c:
                dst[x, y] = pal[c] + (255,)
    return out


dirt = Image.open(os.path.join(PICS, "dirt_pile.png"))
sprout = Image.open(os.path.join(PICS, "sprout.png"))
sheet = Image.new("RGBA", (9 * 16, 32 * len(berries)), (0, 0, 0, 0))
for r, (name, *_rest) in enumerate(berries):
    p = os.path.join(PICS, name.lower() + ".png")
    sl = slots.get(name, [3, 4, 2, 2, 2])
    if not os.path.exists(p):
        continue
    tree = Image.open(p)
    sheet.paste(recolour(dirt, NPC[sl[0]]), (0, r * 32 + 16))
    for k in range(2):
        sheet.paste(recolour(sprout.crop((k * 16, 0, k * 16 + 16, 16)), NPC[sl[1]]), (16 * (1 + k), r * 32 + 16))
    for k in range(6):
        stage = 2 + k // 2
        sheet.paste(recolour(tree.crop((k * 16, 0, k * 16 + 16, 32)), NPC[sl[stage]]), (16 * (3 + k), r * 32))
sheet.save(os.path.join(WORLD, "berrytrees.png"), optimize=True)

lines = ["// Generated by tools/emerald_berries.py from pret/pokeemerald (src/berry.c): Emerald's berries, in its order",
         "// (the rows of World/berrytrees.png). {name, hours per growth stage, most, fewest, spicy, dry, sweet, bitter, sour, smoothness}",
         "static const BerryInfo kBerries[] = {"]
for name, hrs, mx, mn, fl, sm in berries:
    lines.append('    {"%s Berry", %d, %d, %d, {%s}, %d},' % (name, hrs, mx, mn, ", ".join(map(str, fl)), sm))
lines.append("};")
open(os.path.join(SRC, "berries.inc"), "w").write("\n".join(lines) + "\n")
print(len(berries), "berries")

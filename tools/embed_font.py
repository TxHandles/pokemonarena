#!/usr/bin/env python3
"""Bakes fonts/PixelifySans-Medium.ttf into src/font_data.cpp (the game's text font, SIL Open Font License,
see fonts/OFL.txt). Run again only if the font file changes:   python tools/embed_font.py
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(ROOT, "fonts", "PixelifySans-Medium.ttf"), "rb").read()
out = ["// Generated by tools/embed_font.py from fonts/PixelifySans-Medium.ttf (Pixelify Sans Medium with a wider space, SIL OFL 1.1).", "",
       f"extern const unsigned int kFontDataSize = {len(data)};",
       f"extern const unsigned char kFontData[{len(data)}] = {{"]
for k in range(0, len(data), 32):
    out.append(",".join(str(b) for b in data[k:k + 32]) + ",")
out.append("};")
open(os.path.join(ROOT, "src", "font_data.cpp"), "w").write("\n".join(out) + "\n")

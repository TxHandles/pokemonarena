#!/usr/bin/env python3
"""Emerald's Pokemon Contests, from pret/pokeemerald: src/contest_data.inc for src/contest.cpp.

    emerald_contest.py <pokeemerald dir> [src dir]

kContestMoves: {move (upper case, as Emerald spells it), category, effect, combo starter, combos it follows}
kContestEffects: {kind, appeal, jam, description}
kContestOpponents: {trainer, nickname, species, rank, categories (bit per category), moves, cool, beauty, cute, smart, tough, sheen}
Categories: 0 Cool, 1 Beauty, 2 Cute, 3 Smart, 4 Tough. Ranks: 0 Normal, 1 Super, 2 Hyper, 3 Master."""
import os, re, sys

E = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src")
rd = lambda p: open(os.path.join(E, p), encoding="utf-8", errors="replace").read()

names = dict(re.findall(r"\[(MOVE_\w+)\]\s*=\s*_\(\"(.*?)\"\)", rd("src/data/text/move_names.h")))
CAT = {"COOL": 0, "BEAUTY": 1, "CUTE": 2, "SMART": 3, "TOUGH": 4}
effects_c = rd("include/constants/contest.h")
EFF = {n: int(v) for n, v in re.findall(r"#define (CONTEST_EFFECT_\w+)\s+(\d+)", effects_c) if not n.startswith("CONTEST_EFFECT_TYPE")}
ETYPE = {n: int(v) for n, v in re.findall(r"#define (CONTEST_EFFECT_TYPE_\w+)\s+(\d+)", effects_c)}

src = rd("src/data/contest_moves.h")
moves = []
for m in re.finditer(r"\[(MOVE_\w+)\]\s*=\s*\{\s*\n(.*?)\n    \},", src, re.S):
    b = m.group(2)
    eff = re.search(r"\.effect\s*=\s*(\w+)", b)
    cat = re.search(r"\.contestCategory\s*=\s*CONTEST_CATEGORY_(\w+)", b)
    st = re.search(r"\.comboStarterId\s*=\s*(\w+)", b)
    combo = re.search(r"\.comboMoves\s*=\s*\{([^}]*)\}", b)
    if not eff or not cat or m.group(1) not in names:
        continue
    starter = st.group(1).replace("COMBO_STARTER_", "") if st and st.group(1) != "0" else ""
    follows = [c.strip().replace("COMBO_STARTER_", "") for c in (combo.group(1) if combo else "").split(",") if c.strip() and c.strip() != "0"]
    moves.append((names[m.group(1)], CAT[cat.group(1)], EFF[eff.group(1)], starter, "|".join(follows)))

texts = {}
cur = None
for line in rd("data/text/contest_strings.inc").split("\n"):
    mm = re.match(r"^(\w+)::", line)
    if mm:
        cur = mm.group(1); texts[cur] = ""; continue
    mm = re.match(r'\s*\.string\s+"(.*)"', line)
    if mm and cur:
        texts[cur] += mm.group(1)
desc = dict(re.findall(r"\[(CONTEST_EFFECT_\w+)\]\s*=\s*(\w+),", rd("src/data/contest_text_tables.h").split("gContestEffectDescriptionPointers[] =")[-1]))
effects = {}
for m in re.finditer(r"\[(CONTEST_EFFECT_\w+)\]\s*=\s*\{(.*?)\}", src.split("gContestEffects[]")[1], re.S):
    b = m.group(2)
    t = re.search(r"\.effectType\s*=\s*(\w+)", b).group(1)
    ap = int(re.search(r"\.appeal\s*=\s*(\d+)", b).group(1))
    jam = int(re.search(r"\.jam\s*=\s*(\d+)", b).group(1))
    d = texts.get(desc.get(m.group(1), ""), "").replace("\\n", " ").replace("$", "").replace("POKéMON", "Pokemon").replace("é", "e")
    d = re.sub(r"\s+", " ", d).strip()
    d = d[:1] + d[1:].lower() if d else d
    effects[EFF[m.group(1)]] = (ETYPE[t], ap, jam, d.replace('"', "'"))

opp = []
osrc = rd("src/data/contest_opponents.h").split("gContestOpponents[]")[1]
spname = lambda s: "-".join(p.capitalize() for p in s.split("_")) if s not in ("MR_MIME", "HO_OH", "NIDORAN_F", "NIDORAN_M", "FARFETCHD") else {"MR_MIME": "Mr. Mime", "HO_OH": "Ho-Oh", "NIDORAN_F": "Nidoran F", "NIDORAN_M": "Nidoran M", "FARFETCHD": "Farfetch'd"}[s]
RANK = {"NORMAL": 0, "SUPER": 1, "HYPER": 2, "MASTER": 3}
for m in re.finditer(r"\[CONTEST_OPPONENT_\w+\]\s*=\s*\{(.*?)\n    \},", osrc, re.S):
    b = m.group(1)
    g = lambda k: re.search(r"\." + k + r"\s*=\s*([^,\n]+)", b).group(1).strip()
    try:
        species = spname(g("species").replace("SPECIES_", ""))
        nick = re.search(r'\.nickname\s*=\s*_\("(.*?)"\)', b).group(1).title()
        trainer = re.search(r'\.trainerName\s*=\s*_\("(.*?)"\)', b).group(1).title()
        rank = RANK[g("whichRank").replace("CONTEST_RANK_", "")]
        pools = sum(1 << k for k, c in enumerate(("Cool", "Beauty", "Cute", "Smart", "Tough")) if g("aiPool_" + c) == "TRUE")
        mv = [names.get(x.strip(), "") for x in re.search(r"\.moves\s*=\s*\{([^}]*)\}", b).group(1).split(",") if x.strip()]
        st = [int(g(k)) for k in ("cool", "beauty", "cute", "smart", "tough", "sheen")]
    except (AttributeError, KeyError, ValueError):
        continue
    opp.append((trainer, nick, species, rank, pools, mv, st))

L = ["// Generated by tools/emerald_contest.py from pret/pokeemerald: Emerald's Pokemon Contests (moves, effects, opponents).",
     "// Categories 0 Cool, 1 Beauty, 2 Cute, 3 Smart, 4 Tough; ranks 0 Normal, 1 Super, 2 Hyper, 3 Master.",
     "static const ContestMoveInfo kContestMoves[] = {"]
L += ['    {"%s", %d, %d, "%s", "%s"},' % m for m in moves]
L += ["};", "static const ContestEffectInfo kContestEffects[] = {"]
for k in range(max(effects) + 1):
    t, ap, jam, d = effects.get(k, (0, 0, 0, ""))
    L.append('    {%d, %d, %d, "%s"},' % (t, ap, jam, d))
L += ["};", "static const ContestOpponentInfo kContestOpponents[] = {"]
for tr, nick, sp, rank, pools, mv, st in opp:
    L.append('    {"%s", "%s", "%s", %d, %d, {"%s"}, {%s}},' % (tr, nick, sp, rank, pools, '", "'.join((mv + [""] * 4)[:4]), ", ".join(map(str, st))))
L.append("};")
open(os.path.join(OUT, "contest_data.inc"), "w").write("\n".join(L) + "\n")
print(len(moves), "contest moves,", len(effects), "effects,", len(opp), "opponents")

#!/usr/bin/env python3
"""Writes src/hm_compat.inc: which Pokemon can learn the field moves (HM01 Cut .. HM08 Dive), from a
PokeAPI checkout's CSVs (machine or level-up learnsets, Gen 1-7).
    python tools/gen_hm_compat.py <path to pokeapi/data/v2/csv>
"""
import csv, glob, os, sys
P = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hm = {15: 'Cut', 19: 'Fly', 57: 'Surf', 70: 'Strength', 148: 'Flash', 249: 'Rock Smash', 127: 'Waterfall', 291: 'Dive'}
spec = {int(r['species_id']): int(r['id']) for r in csv.DictReader(open(P + '/pokemon.csv')) if r['is_default'] == '1'}
learn = {}
for r in csv.DictReader(open(P + '/pokemon_moves.csv')):
    m = int(r['move_id'])
    if m in hm and r['pokemon_move_method_id'] in ('4', '1') and int(r['version_group_id']) <= 17:
        learn.setdefault(int(r['pokemon_id']), set()).add(hm[m])
out = []
for d in sorted(glob.glob(os.path.join(ROOT, 'Pokemon/*/pokemon.txt'))):
    nm = dex = None
    for line in open(d, errors='ignore').read().split('\n'):
        if line.startswith('name') and '=' in line and nm is None: nm = line.split('=', 1)[1].split('#')[0].strip()
        if line.startswith('dex') and '=' in line and dex is None:
            try: dex = int(line.split('=', 1)[1].split('#')[0])
            except ValueError: pass
        if line.startswith('mega_of'): dex = None; break
    s = learn.get(spec.get(dex), set()) if nm and dex else set()
    if s: out.append((nm, sorted(s)))
lines = ['// Generated by tools/gen_hm_compat.py from PokeAPI (machine/level learnsets, Gen 1-7): which Pokemon can learn each',
         '// field move (HM01 Cut .. HM08 Dive). {species name, "Cut|Fly|..."}',
         'static const struct { const char* species; const char* moves; } kHmCompat[] = {']
lines += ['    {"%s", "%s"},' % (nm, '|'.join(s)) for nm, s in out]
lines.append('};')
open(os.path.join(ROOT, 'src/hm_compat.inc'), 'w').write('\n'.join(lines) + '\n')
print(len(out), 'Pokemon')

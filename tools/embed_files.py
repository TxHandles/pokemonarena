#!/usr/bin/env python3
"""Bakes the game's data files (Pokemon/, Badges/, story.txt, map.png) into src/embedded_files.inc so the
exe carries them. At startup the game writes back any of these files that are missing next to it.
Run this again after changing anything in Pokemon/, story.txt or map.png:   python tools/embed_files.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_NAMES = {"load_log.txt", "MOVE-LIST.txt"}
SKIP_DIRS = {"converted"}

files = []
for rel in ["story.txt", "wild.txt", "map.png"]:
    if os.path.exists(os.path.join(ROOT, rel)):
        files.append(rel)
for top in ["Pokemon", "Badges"]:
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, top)):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if f in SKIP_NAMES:
                continue
            files.append(os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/"))

# The bytes go into several src/embedded_data_NN.cpp files (a few MB each) so no single file is too
# big for the compiler; src/embedded_files.inc only declares them and lists the files.
import glob
for old in glob.glob(os.path.join(ROOT, "src", "embedded_data_*.cpp")):
    os.remove(old)
CHUNK = 4 * 1024 * 1024
chunks, cur, curSize = [], [], 0
for i, rel in enumerate(files):
    size = os.path.getsize(os.path.join(ROOT, rel))
    if cur and curSize + size > CHUNK:
        chunks.append(cur); cur, curSize = [], 0
    cur.append(i); curSize += size
if cur:
    chunks.append(cur)
for n, idxs in enumerate(chunks):
    out = ["// Generated by tools/embed_files.py - do not edit by hand.", ""]
    for i in idxs:
        data = open(os.path.join(ROOT, files[i]), "rb").read()
        out.append(f"extern const unsigned char kFile{i}[{max(1, len(data))}] = {{")
        for k in range(0, len(data), 32):
            out.append(",".join(str(b) for b in data[k:k + 32]) + ",")
        if not data:
            out.append("0")
        out.append("};")
    open(os.path.join(ROOT, "src", f"embedded_data_{n:02d}.cpp"), "w").write("\n".join(out) + "\n")

out = ["// Generated by tools/embed_files.py - do not edit by hand.", ""]
entries = []
for i, rel in enumerate(files):
    size = os.path.getsize(os.path.join(ROOT, rel))
    out.append(f"extern const unsigned char kFile{i}[{max(1, size)}];")
    entries.append(f'    {{"{rel}", kFile{i}, {size}}},')
out.append("")
out.append("static const EmbeddedFile kEmbeddedFiles[] = {")
out += entries
out.append("};")
open(os.path.join(ROOT, "src", "embedded_files.inc"), "w").write("\n".join(out) + "\n")
print(f"embedded {len(files)} files in {len(chunks)} data files")

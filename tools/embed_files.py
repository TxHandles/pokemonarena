#!/usr/bin/env python3
"""Bakes the game's data files (Pokemon/, World/, Sounds/, story.txt, the region maps...) into the exe. At startup
the game writes back any of these files that are missing next to it.
Run this again after changing any of them:   python tools/embed_files.py

It writes (all generated, not in git):
  src/embedded_blob.bin    every file one after another; text and other files that squeeze well are deflated
                           (PNG and OGG are compressed already and go in as they are)
  src/embedded_files.inc   the list: path, where it starts in the blob, its size, its packed size (0 = stored)
  src/embedded_blob.cpp    puts the blob in the exe: GCC / Clang / MinGW with the assembler's .incbin,
                           Visual Studio through src/embedded_blob.rc (a Windows resource)
  src/embedded_blob.rc     (Visual Studio only; CMakeLists.txt adds it there)
The blob is linked in as it is, so building takes seconds instead of compiling a hundred MB of C arrays."""
import os
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
SKIP_NAMES = {"load_log.txt", "MOVE-LIST.txt"}
SKIP_DIRS = {"converted", "__pycache__"}
STORED = (".png", ".ogg", ".jpg", ".jpeg", ".webp", ".mp3", ".zip")

files = []
for rel in ["story.txt", "wild.txt", "map.png", "johto.png", "hoenn.png", "sinnoh.png", "unova.png"]:
    if os.path.exists(os.path.join(ROOT, rel)):
        files.append(rel)
for top in ["Pokemon", "Badges", "Leaders", "World", "Sounds"]:
    for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, top)):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if f in SKIP_NAMES:
                continue
            files.append(os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/"))

# the old way's leftovers
for old in os.listdir(SRC):
    if old.startswith("embedded_data_") and old.endswith(".cpp"):
        os.remove(os.path.join(SRC, old))

blob = bytearray()
entries = []
raw_total = 0
for rel in files:
    data = open(os.path.join(ROOT, rel), "rb").read()
    raw_total += len(data)
    packed = 0
    if not rel.lower().endswith(STORED) and len(data) > 64:
        c = zlib.compressobj(9, zlib.DEFLATED, -15)   # raw deflate: raylib's DecompressData reads it
        z = c.compress(data) + c.flush()
        if len(z) < len(data) * 0.9:
            data, packed = z, len(z)
    while len(blob) % 4:
        blob.append(0)
    entries.append((rel, len(blob), os.path.getsize(os.path.join(ROOT, rel)), packed))
    blob += data
blob += b"\0" * 16   # (never empty)
open(os.path.join(SRC, "embedded_blob.bin"), "wb").write(blob)

esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
out = ["// Generated by tools/embed_files.py - do not edit by hand.",
       "// {path, offset in the blob, size, packed size (0: stored as it is)}",
       "static const EmbeddedFile kEmbeddedFiles[] = {"]
out += [f'    {{"{esc(rel)}", {off}u, {size}u, {packed}u}},' for rel, off, size, packed in entries]
out.append("};")
open(os.path.join(SRC, "embedded_files.inc"), "w").write("\n".join(out) + "\n")

blob_path = os.path.join(SRC, "embedded_blob.bin").replace("\\", "/")
open(os.path.join(SRC, "embedded_blob.cpp"), "w").write(f'''// Generated by tools/embed_files.py - do not edit by hand. The game's data files (embedded_blob.bin) in the exe.
#include <cstddef>
#if defined(_MSC_VER)
#define WIN32_LEAN_AND_MEAN
#define NOMINMAX
#include <windows.h>
const unsigned char* EmbeddedBlob() {{   // embedded_blob.rc: the blob is resource 101
    static const unsigned char* p = nullptr;
    if (!p) {{
        HRSRC r = FindResourceA(nullptr, MAKEINTRESOURCEA(101), MAKEINTRESOURCEA(10));
        HGLOBAL h = r ? LoadResource(nullptr, r) : nullptr;
        p = h ? (const unsigned char*)LockResource(h) : nullptr;
    }}
    return p;
}}
#else
#if defined(_WIN32)
#define ARENA_RODATA ".section .rdata,\\"dr\\"\\n"
#else
#define ARENA_RODATA ".section .rodata\\n"
#endif
__asm__(ARENA_RODATA
        ".balign 16\\n"
        ".globl arena_embedded_blob\\n"
        "arena_embedded_blob:\\n"
        ".incbin \\"{esc(blob_path)}\\"\\n"
        ".text\\n");
extern "C" const unsigned char arena_embedded_blob[] __asm__("arena_embedded_blob");
const unsigned char* EmbeddedBlob() {{ return arena_embedded_blob; }}
#endif
''')
open(os.path.join(SRC, "embedded_blob.rc"), "w").write(f'// Generated by tools/embed_files.py (Visual Studio builds).\n101 RCDATA "{esc(blob_path)}"\n')
print(f"embedded {len(files)} files: {raw_total / 1e6:.1f} MB -> {len(blob) / 1e6:.1f} MB blob")
